// Freeze the small, version-specific bridge and its private Pele registry into one ESM module.
import fs from 'node:fs/promises';
import { build } from 'esbuild';

const root = new URL('../', import.meta.url);
const expected = '1.12.0';
const pkg = JSON.parse(await fs.readFile(new URL('node_modules/pele/package.json', root), 'utf8'));
if (pkg.version !== expected) throw new Error(`the Pele bridge targets ${expected}, found ${pkg.version}`);
const result = await build({
  entryPoints: [new URL('src/pele/bridge.js', root).pathname],
  bundle: true, format: 'esm', platform: 'browser', target: 'es2022',
  minify: true, legalComments: 'eof', write: false,
  banner: { js: `// Pele ${expected}, MIT. Generated by scripts/vendor-pele.js; see VENDORED.md.` },
});
const files = new Map([
  ['runtime.js', result.outputFiles[0].text],
  ['runtime.d.ts', "export * from '../../src/pele/bridge.js';\n"],
  ['LICENSE', await fs.readFile(new URL('node_modules/pele/LICENSE', root), 'utf8')],
  ['VENDORED.md', `Private Pele ${expected} flowchart runtime, generated by \`npm run vendor:pele\`.\n\nSource: https://github.com/obsidianmd/pele, MIT license in LICENSE. Built from the published \`pele/core\` and \`pele/diagrams/flowchart\` exports and src/pele/bridge.js with the versions locked in package-lock.json.\n\nPele's source is unchanged. The bridge calls its existing fourth flowchart-render argument to capture measured geometry and draw a supplied layout. Bundling gives the bridge its own registry so it cannot replace an application's Pele renderer. Updating Pele requires updating the explicit version guard, regenerating, and running the integration and native-parity tests.\n`],
]);
const check = process.argv.includes('--check');
for (const [name, content] of files) {
  const path = new URL(`vendor/pele/${name}`, root);
  if (check) {
    if (await fs.readFile(path, 'utf8') !== content) throw new Error(`${name} differs; run npm run vendor:pele`);
  } else await fs.writeFile(path, content);
}
console.log(`Pele ${expected} private bridge ${check ? 'matches' : 'generated'}`);
